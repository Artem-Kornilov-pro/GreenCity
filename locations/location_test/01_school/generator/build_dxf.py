# Тестовый участок 01: территория школы, 2,2 га (170 x 130 м).
#
# П-образное здание школы (3 этажа) открыто на юг, к улице: между крыльями --
# парадный двор с площадью у главного входа, к ней от ворот в южной ограде
# ведёт аллея. Восточнее -- стадион (мини-футбольное поле) и спортплощадка,
# западнее -- площадка младших классов, на северо-западе -- хоздвор: проезд
# с западной улицы, парковка, трансформаторная подстанция.
#
# Существующая растительность: ряд старых лип вдоль южной ограды (с разрывом у
# ворот и над сетями), тополя вдоль западной ограды, группа берёз у площадки,
# две голубые ели у парадной площади и стриженая спирея вдоль неё.
#
# Сети заходят с разных сторон: водопровод и канализация -- с южной улицы
# через парадный двор, теплосеть -- с востока между стадионом и
# спортплощадкой, силовой кабель -- с западной улицы под проездом в ТП и от
# неё к зданию, кабель связи -- с юга вдоль западного крыла.
#
# Что проверять: защитная посадка по периметру ограды, отступы от окон школы,
# стадион и площадки не засаживаются, старые липы и тополя сохраняются.
#
# Синтетический участок, без привязки к реальному адресу. Запуск из этой папки:
#   python build_dxf.py
# Результат пишется уровнем выше: ../01_school.dxf

import sys
from pathlib import Path

from shapely.geometry import box
from shapely.ops import unary_union

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from dxf_kit import Site  # noqa: E402

site = Site()
site.boundary(box(0, 0, 170, 130))

# --- Здание школы: главный корпус + два крыла (П открыто на юг) ---------------
main = box(40, 92, 130, 110)
west_wing = box(40, 62, 58, 92)
east_wing = box(112, 62, 130, 92)
school = site.building(
    [main, west_wing, east_wing],
    levels=3,
    floor_h=3.6,
    name="Школа",
    entrances=[(85, 92), (49, 62), (121, 62), (60, 110)],
)

# --- Дорожки, парадная площадь -------------------------------------------------
paths = unary_union([
    box(82, 0, 88, 80),       # аллея от ворот к главному входу
    box(68, 80, 102, 92),     # парадная площадь у главного входа
    box(8, 40, 162, 43),      # поперечная дорожка: площадка младших -- стадион
    box(47.5, 43, 50.5, 62),  # к входу западного крыла
    box(119.5, 43, 122.5, 62),  # к входу восточного крыла
    box(19, 43, 22, 55),      # к площадке младших классов
    box(150, 43, 153, 55),    # к стадиону
    box(150, 32, 153, 40),    # к спортплощадке
    box(58.5, 110, 61.5, 116),  # хозяйственный вход -- к проезду
])
site.area(paths, "PATHS")

# --- Хоздвор: проезд с западной улицы, парковка, ТП ---------------------------
driveway = box(0, 116, 72, 122)
site.area(driveway, "ROAD")
site.curbs(driveway)
site.parking(box(6, 100, 34, 116))
tp = box(76, 117, 82, 123)
site.small_structure(tp, "TRANSFORMER_SUBSTATION", 3.0, "ТП")

# --- Площадки ------------------------------------------------------------------
site.area(box(8, 55, 33, 75), "PLAYGROUND")
site.area(box(138, 55, 166, 115), "PLAYGROUND_SPORTS")  # стадион
site.area(box(138, 12, 166, 32), "PLAYGROUND_SPORTS")  # спортплощадка
site.label("Стадион", 146, 85, 3)
site.label("Спортплощадка", 141, 22, 2)
site.label("Площадка младших классов", 9, 65, 1.5)

# --- Сети ----------------------------------------------------------------------
site.utility("WATER_SUPPLY_B1", [(100, 0), (100, 92)])
site.utility("SEWER_K1", [(66, 92), (66, 0)])
site.utility("HEATING_T1", [(170, 48), (125, 48), (125, 62)])
site.utility("POWER_CABLE", [(0, 119), (76, 119)])
site.utility("POWER_CABLE", [(79, 117), (79, 110)])
site.utility("CABLE_COMM", [(36, 0), (36, 70), (40, 70)])

# --- Существующая растительность ----------------------------------------------
for x in (8, 17, 26, 44, 53, 71, 107, 116, 125, 134, 143, 152, 161):
    site.plant("TREE", "Липа мелколистная", x, 4, crown=4.0)
for y in (24, 34, 50, 62, 74, 86):
    site.plant("TREE", "Тополь бальзамический", 4, y, crown=5.0)
for x, y in ((12, 84), (20, 88), (28, 83), (15, 94), (26, 94)):
    site.plant("TREE", "Береза повислая", x, y, crown=3.5)
for x, y in ((77, 74), (93, 74)):
    site.plant("TREE", "Ель колючая", x, y, crown=2.5)
for i in range(7):
    site.plant("BUSH", "Спирея Вангутта", 70 + i * 1.5, 78, crown=0.8)
for i in range(5):
    site.plant("BUSH", "Спирея Вангутта", 90.5 + i * 1.5, 78, crown=0.8)

# --- Освещение, скамейки -------------------------------------------------------
for y in (10, 24, 37, 52, 66):
    site.lamp(80, y)
for x in (15, 35, 55, 95, 115, 135, 155):
    site.lamp(x, 45)
for x in (20, 45, 68):
    site.lamp(x, 124)
site.lamp(4, 108)
site.lamp(36, 108)
for x in (72, 78, 92, 98):
    site.bench(x, 86)
for x in (13, 28):
    site.bench(x, 77)

site.save(str(Path(__file__).resolve().parents[1] / "01_school.dxf"))

# Тестовый участок 03: реконструкция двора жилого квартала, 2,7 га (180 x 150 м).
#
# Квартал-каре: две панельные 9-этажки (север и юг), 12-этажный дом на западе
# и две 5-этажки на востоке, все подъезды -- во двор. Кольцевой пожарный
# проезд идёт в 14 м от фасадов: между домом и проездом -- тротуар у фасада и
# полоса земли под посадку, через неё к подъездам ведут дорожки. Внутри
# кольца -- парковочные карманы, детская и спортивная площадки,
# трансформаторная подстанция и одноэтажный ЦТП, от которого теплосеть
# расходится по всем домам через двор. Въезды -- через разрывы между домами.
#
# Сети плотные, как в старом квартале: водопровод кольцом по периметру
# квартала снаружи домов, канализация вдоль дворовых фасадов (в 3 м от стены),
# теплосеть и силовые кабели -- поперёк двора, газ -- к пятиэтажкам, кабель
# связи -- под северной ветвью проезда.
#
# Существующая растительность: ~25 взрослых деревьев (липы, берёзы, клёны,
# тополя, ели) на газонах двора и кусты у детской площадки; все стоят с
# соблюдением норм.
#
# Что проверять: существующие деревья и газоны сохраняются, новые посадки --
# в промежутках между ними и в полосах между домами и проездом; проезд,
# площадки, парковки и коридоры сетей не засажены; нарушений 0.
#
# Синтетический участок, без привязки к реальному адресу. Запуск из этой папки:
#   python build_dxf.py
# Результат пишется уровнем выше: ../03_courtyard_renovation.dxf

import random
import sys
from pathlib import Path

from shapely.geometry import LineString, Point, box
from shapely.ops import unary_union

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from dxf_kit import Site  # noqa: E402

site = Site()
site.boundary(box(0, 0, 180, 150))

# --- Дома, подъезды во двор ------------------------------------------------------
houses = [
    ("Дом 1", box(20, 128, 136, 140), 9, [(x, 128) for x in (32, 55, 78, 101, 124)]),
    ("Дом 2", box(44, 10, 160, 22), 9, [(x, 22) for x in (56, 79, 102, 125, 148)]),
    ("Дом 3", box(8, 34, 20, 116), 12, [(20, y) for y in (50, 75, 100)]),
    ("Дом 4", box(160, 30, 172, 75), 5, [(160, y) for y in (42, 62)]),
    ("Дом 5", box(160, 88, 172, 125), 5, [(160, y) for y in (98, 115)]),
]
footprints = []
for name, fp, levels, doors in houses:
    footprints.append(site.building([fp], levels=levels, name=name, entrances=doors))
ctp = box(100, 88, 112, 96)
site.building([ctp], levels=1, floor_h=4.5, name="ЦТП", windows=False)

# --- Кольцевой проезд (в 14 м от фасадов), въезды, парковки -----------------------
roads = unary_union([
    box(34, 109.5, 146, 114),  # северная ветвь кольца
    box(34, 36, 146, 40.5),  # южная
    box(34, 36, 38.5, 114),  # западная
    box(141.5, 36, 146, 114),  # восточная
    box(34, 0, 38.5, 36),  # въезд с юга между домами 2 и 3
    box(141.5, 114, 146, 150),  # въезд с севера между домами 1 и 5
])
site.area(roads, "ROAD")
site.curbs(roads)
parking_s = box(48, 40.5, 92, 45.8)
parking_n = box(62, 104.2, 118, 109.5)
site.parking(parking_s)
site.parking(parking_n)

# --- Тротуары у фасадов, дорожки ----------------------------------------------
site.area(unary_union([
    box(20, 126, 136, 128), box(44, 22, 160, 24), box(20, 34, 22, 116),
    box(158, 30, 160, 75), box(158, 88, 160, 125),
]), "SIDEWALK")
paths = [box(38.5, 84, 141.5, 87), box(94, 40.5, 97, 104.2)]
for _name, _fp, _, doors in houses:
    for x, y in doors:  # от тротуара у фасада через полосу к проезду
        if y == 128:
            paths.append(box(x - 1.25, 114, x + 1.25, 126))
        elif y == 22:
            paths.append(box(x - 1.25, 24, x + 1.25, 36))
        elif x == 20:
            paths.append(box(22, y - 1.25, 34, y + 1.25))
        else:
            paths.append(box(146, y - 1.25, 158, y + 1.25))
paths = unary_union(paths)
site.area(paths, "PATHS")

# --- Площадки, ТП ----------------------------------------------------------------
playground = box(56, 60, 84, 80)
sports = box(106, 50, 134, 66)
site.area(playground, "PLAYGROUND")
site.area(sports, "PLAYGROUND_SPORTS")
site.label("Детская площадка", 59, 70, 1.8)
site.label("Спортплощадка", 112, 58, 1.8)
tp = box(44, 96, 50, 101)
site.small_structure(tp, "TRANSFORMER_SUBSTATION", 3.0, "ТП")

# --- Сети ------------------------------------------------------------------------
networks = {
    "HEATING_T1": [
        [(180, 79), (128, 79), (128, 92), (112, 92)],  # ввод в ЦТП с востока
        [(100, 92), (20, 92)],  # ЦТП -> дом 3
        [(106, 96), (106, 128)],  # ЦТП -> дом 1
        [(103, 88), (103, 22)],  # ЦТП -> дом 2
        [(112, 94), (160, 94)],  # ЦТП -> дом 5
        [(154, 79), (154, 70), (160, 70)],  # -> дом 4
    ],
    "WATER_SUPPLY_B1": [
        [(0, 146), (180, 146)], [(3, 146), (3, 4)], [(0, 4), (180, 4)], [(177, 4), (177, 146)],
        [(50, 146), (50, 140)], [(110, 146), (110, 140)], [(3, 75), (8, 75)],
        [(70, 4), (70, 10)], [(130, 4), (130, 10)], [(177, 52), (172, 52)], [(177, 106), (172, 106)],
        [(143.75, 146), (143.75, 102), (110, 102), (110, 96)],  # -> ЦТП под северным въездом
    ],
    "SEWER_K1": [
        [(24, 125), (139, 125), (139, 150)],
        [(23, 114), (23, 25), (180, 25)],
        [(157, 122), (157, 25)],
    ],
    "GAS_PIPE": [[(180, 84.5), (166, 84.5)], [(166, 84.5), (166, 75)], [(166, 84.5), (166, 88)]],
    "POWER_CABLE": [
        [(0, 121), (27, 121), (27, 98.5), (44, 98.5)],  # ввод в ТП
        [(47, 101), (47, 128)],  # ТП -> дом 1
        [(44, 97.5), (20, 97.5)],  # ТП -> дом 3
        [(47, 96), (47, 22)],  # ТП -> дом 2
        [(50, 99), (160, 99)],  # ТП -> дом 5
        [(180, 40), (172, 40)],  # дом 4 -- с улицы
    ],
    "CABLE_COMM": [[(143.75, 150), (143.75, 111.75), (30, 111.75)]],
}
for layer, runs in networks.items():
    for run in runs:
        site.utility(layer, run)

# --- Существующие газоны двора -----------------------------------------------------
yard = box(38.5, 40.5, 141.5, 109.5)
grass = yard.difference(unary_union([
    parking_s.buffer(1), parking_n.buffer(1), paths.buffer(0.5), playground.buffer(1.5),
    sports.buffer(1.5), tp.buffer(1.5), ctp.buffer(1.5),
]))
site.area(grass, "GRASS", min_area=20)

# --- Существующая растительность ----------------------------------------------
# Деревья -- на газонах двора, вне охранных зон сетей и с отступами от
# площадок, проезда и зданий (липа и клён -- 10 м от здания, 743-ПП);
# детерминированно (фиксированный seed).
corridors = unary_union([LineString(run).buffer(6.0) for runs in networks.values() for run in runs])
free = grass.difference(unary_union([
    corridors, paths.buffer(2.5), playground.buffer(3), sports.buffer(3), roads.buffer(3),
    parking_s.buffer(3), parking_n.buffer(3), tp.buffer(5), ctp.buffer(10.5),
    *[fp.buffer(10.5) for fp in footprints],
]))
SPECIES = [
    ("Липа мелколистная", 4.5), ("Береза повислая", 3.5), ("Клен остролистный", 4.0),
    ("Тополь бальзамический", 5.5), ("Ель обыкновенная", 2.5),
]
WEIGHTS = [10, 8, 8, 6, 3]
rng = random.Random(2026)
minx, miny, maxx, maxy = free.bounds
trees = []
for _ in range(20000):
    if len(trees) >= 40:
        break
    p = Point(rng.uniform(minx, maxx), rng.uniform(miny, maxy))
    if free.contains(p) and all(p.distance(q) >= 6.5 for q in trees):
        trees.append(p)
for p in trees:
    species, crown = rng.choices(SPECIES, WEIGHTS)[0]
    site.plant("TREE", species, round(p.x, 2), round(p.y, 2), crown=crown)
# Кусты -- группами вдоль западной и южной стороны детской площадки.
for i, species in enumerate(("Сирень обыкновенная", "Спирея Вангутта", "Чубушник венечный")):
    for k in range(4):
        site.plant("BUSH", species, 53.5, 62 + i * 6.5 + k * 1.5, crown=1.0)
for k in range(8):
    site.plant("BUSH", "Спирея Вангутта", 60 + k * 3, 57.5, crown=0.9)

# --- Освещение, скамейки -----------------------------------------------------------
# Только там, где редактор не подсветит объект нарушением (см. Site.is_clear).
lamps = [(x, 82.6) for x in (45, 65, 85, 115, 135)]
lamps += [(92.4, y) for y in (52, 70, 98)]
lamps += [(40.3, y) for y in (50, 75, 100)] + [(139.7, y) for y in (50, 75, 100)]
for x, y in lamps:
    if site.is_clear(x, y):
        site.lamp(x, y)
for x in (60, 66, 72, 78):
    if site.is_clear(x, 82.8):
        site.bench(x, 82.8)
for y in (48, 56, 74):
    if site.is_clear(98.8, y):
        site.bench(98.8, y, 90)

site.save(str(Path(__file__).resolve().parents[1] / "03_courtyard_renovation.dxf"))
